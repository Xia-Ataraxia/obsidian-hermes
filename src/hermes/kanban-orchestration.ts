/** Orchestration settings and profile descriptions (O1-O8), the web's OrchestrationPanel as a modal. */
import { Modal, Notice, parseYaml, Setting, setTooltip, type App, type ExtraButtonComponent } from "obsidian";
import type { Outcome } from "./data";
import type { BoardRead, KanbanClient } from "./kanban";
import { confirmed, message } from "./kanban-drawer";
import { failBox } from "./ui";

type Key = "orchestrator_profile" | "default_assignee" | "auto_decompose";

export interface OrchestrationHost {
  readonly app: App;
  readonly kanban: KanbanClient;
  readonly alias: string;
  read(): BoardRead | null;
  /** Why a write must not go out (the view closed, or its SSH host changed), else null. */
  moved(): string | null;
  reload(): Promise<void>;
}

const on = (v?: string): boolean => !/^(false|no|off|0)$/i.test(v ?? "");

export class OrchestrationModal extends Modal {
  /** Only these two fields of profile.yaml are kept, and only here: nothing reaches the disk cache. */
  private readonly metas = new Map<string, { description: string; auto: boolean }>();
  private readonly drafts = new Map<string, string>();
  private status = "";
  private error = false;
  /** Why descriptions could not be read: their rows stay hidden so a blank field never overwrites one. */
  private metaError: string | null = null;
  private busy = false;
  private dismissed = false;

  constructor(private readonly host: OrchestrationHost) { super(host.app); }

  override onOpen(): void {
    this.modalEl.addClass("hm-modal");
    this.setTitle("Orchestration");
    this.render();
    void this.loadMeta();
  }

  override onClose(): void {
    // A write still in flight reports in a Notice: the modal is gone.
    this.dismissed = true;
    this.contentEl.empty();
  }

  private names(): string[] {
    return ["default", ...this.host.read()?.profiles ?? []];
  }

  private render(): void {
    const el = this.contentEl, r = this.host.read(), names = this.names();
    el.empty();
    if (!r) {
      el.createEl("p", { cls: "hm-k-ask-text", text: "The board has not loaded yet." });
      return;
    }
    new Setting(el).setDesc("These settings apply to every board.")
      .addExtraButton(b => b.setIcon("refresh-cw").setTooltip("Reload").setDisabled(this.busy).onClick(() => void this.refresh()));
    const pick = (key: Exclude<Key, "auto_decompose">, name: string, desc = ""): void => {
      const value = r.config[key] ?? "";
      new Setting(el).setName(name).setDesc(desc).addDropdown(d => {
        d.addOption("", "None");
        for (const n of names) d.addOption(n, n);
        if (value && !names.includes(value)) d.addOption(value, `${value} (unknown)`);
        d.setValue(value).setDisabled(this.busy).onChange(v => void this.set(key, v || null));
      });
    };
    pick("orchestrator_profile", "Orchestrator profile", "Owns the root task after fan-out and wakes back up to judge completion.");
    pick("default_assignee", "Default assignee");
    const auto = on(r.config.auto_decompose);
    new Setting(el).setName("Auto-decompose triage tasks")
      .setDesc(auto ? "The dispatcher decomposes new triage tasks automatically." : "Triage tasks stay in triage until you click Decompose.")
      .addToggle(t => t.setValue(auto).setDisabled(this.busy).onChange(v => void this.set("auto_decompose", String(v))));
    el.createDiv({ cls: this.error ? "hm-k-error" : "hm-k-hint", text: this.status });
    new Setting(el).setName("Profile descriptions").setDesc("Descriptions guide the decomposer's routing.").setHeading();
    if (this.metaError !== null) failBox(el, this.metaError, () => void this.refresh());
    else for (const n of names) this.row(el, n);
  }

  private row(el: HTMLElement, name: string): void {
    const meta = this.metas.get(name) ?? { description: "", auto: false };
    let text = this.drafts.get(name) ?? meta.description;
    // Saving an unedited generated description keeps it as user-authored.
    const dirty = (): boolean => text.trim() !== meta.description || meta.auto && !!meta.description;
    const s = new Setting(el).setName(name).setClass("hm-k-desc");
    if (name === "default") s.nameEl.createSpan({ cls: "hm-chip", text: "Default" });
    if (meta.auto && meta.description) setTooltip(s.nameEl.createSpan({ cls: "hm-chip is-review", text: "Auto — review" }), "Generated by a model: review it, then save it as yours");
    let save: ExtraButtonComponent | null = null;
    s.addTextArea(a => a.setPlaceholder("What is this profile good at?").setValue(text).setDisabled(this.busy).onChange(v => {
      text = v;
      this.drafts.set(name, v);
      save?.setDisabled(this.busy || !dirty());
    }));
    s.addExtraButton(b => {
      save = b.setIcon("save").setTooltip("Save the description above as user-authored").setDisabled(this.busy || !dirty()).onClick(() => {
        if (!this.busy && dirty()) void this.run(() => this.host.kanban.describe(this.host.alias, name, text), `Description saved for ${name}.`, "Save failed", "", () => this.described(name));
      });
    });
    s.addExtraButton(b => b.setIcon("sparkles").setTooltip("Auto-generate a description from this profile's skills and model").setDisabled(this.busy)
      .onClick(() => void this.generate(name)));
  }

  private async generate(name: string): Promise<void> {
    if (this.busy || !await confirmed(this.app, "Generate description", `Run a model call on the host to write ${name}'s description? It replaces the current one.`, "Generate")) return;
    await this.run(() => this.host.kanban.describe(this.host.alias, name, null), `Auto-generated description for ${name}.`, "Auto-generate failed", `Generating a description for ${name}…`, () => this.described(name));
  }

  private described(name: string): void {
    this.drafts.delete(name);
    void this.loadMeta();
  }

  private async set(key: Key, value: string | null): Promise<void> {
    const r = this.host.read();
    if (!r) return;
    if (key !== "auto_decompose" && value !== null && !this.names().includes(value)) {
      this.say(`Unknown profile: ${value}`, true);
      return;
    }
    // `config unset` fails on a key the file does not hold, and an empty value is already none.
    if (value === null && !r.config[key]) return;
    await this.run(() => this.host.kanban.setConfig(this.host.alias, key, value), "Settings saved.", "Save failed", "", () => {
      const now = this.host.read();
      if (now) now.config[key] = value ?? "";
      void this.host.reload();
    });
  }

  /** One write at a time, none once the view closed or its host moved; a failure re-renders from the read, which reverts the control. */
  private async run(write: () => Promise<Outcome>, done: string, failed: string, pending: string, after: () => void): Promise<void> {
    const moved = this.host.moved();
    if (moved) {
      this.say(moved, true);
      return;
    }
    if (this.busy) return;
    this.busy = true;
    this.say(pending, false);
    const o = await write().catch((e: unknown): Outcome => ({ ok: false, message: message(e) }));
    this.busy = false;
    if (o.ok) after();
    this.say(o.ok ? done : `${failed}: ${o.message}`, !o.ok);
  }

  private say(text: string, error: boolean): void {
    if (this.dismissed) {
      if (text) new Notice(text, error ? 10_000 : undefined);
      return;
    }
    this.status = text;
    this.error = error;
    this.render();
  }

  private async loadMeta(): Promise<void> {
    if (this.host.moved()) return;
    const names = this.names();
    const s = await this.host.kanban.profileMeta(this.host.alias, names).catch(message);
    if (this.dismissed || this.host.moved()) return;
    this.metaError = typeof s === "string" ? s : null;
    if (typeof s === "string") {
      this.render();
      return;
    }
    for (const n of names) {
      let y: unknown = null;
      try { y = parseYaml(s.get(n) ?? ""); } catch { /* a broken file reads as no description */ }
      const d = (y ?? {}) as { description?: unknown; description_auto?: unknown };
      this.metas.set(n, { description: typeof d.description === "string" ? d.description.trim() : "", auto: d.description_auto === true });
    }
    this.render();
  }

  private async refresh(): Promise<void> {
    this.say("Reloading…", false);
    await this.host.reload();
    if (this.dismissed) return;
    this.say("", false);
    await this.loadMeta();
  }
}
