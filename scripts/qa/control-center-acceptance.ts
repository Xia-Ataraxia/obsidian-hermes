import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { DashboardClient } from "../../src/ui/dashboard-client";
import { ProfileCatalogReader } from "../../src/ui/profile-catalog-reader";
import { readInspectorCron } from "../../src/ui/profile-inspector-data";
import { readExecutionHistory } from "../../src/ui/execution-history-reader";
import { parseScopedIdentity } from "../../src/domain/control-center-validation";
import { createControlCenterFixtureDependencies } from "./control-center-injection";
import { fixtureSession } from "./control-center-fixture";
import { FixtureRefusal, isRecord, ownedPath, verifyHost } from "./fixture-guard";

const identity = verifyHost();
const root = ownedPath(process.argv[2] ?? "");
const lifecycle: unknown = JSON.parse(readFileSync(resolve(root, "lifecycle.json"), "utf8"));
if (!isRecord(lifecycle) || typeof lifecycle.origin !== "string") throw new FixtureRefusal("fixture lifecycle required");
const origin = lifecycle.origin;
const dependencies = createControlCenterFixtureDependencies({ root, origin, sourceRoot: "/Users/beomsu/.hermes/hermes-agent" });
const lease = dependencies.connections.acquire("hermes-fixture");
const client = new DashboardClient(await lease.ready);
const session = await fixtureSession(origin);
const cases: { readonly scenario: string; readonly observable: string; readonly pass: boolean }[] = [];
const check = (scenario: string, pass: boolean, observable: string) => { cases.push({ scenario, observable, pass }); if (!pass) throw new FixtureRefusal(`acceptance failed: ${scenario}`); };
const control = async (scenario: string) => {
  const response = await fetch(`${origin}/__fixture/control`, { method: "POST", headers: session.headers, body: JSON.stringify({ scenario }), signal: AbortSignal.timeout(5000) });
  if (!response.ok) throw new FixtureRefusal("control rejected");
};
const key = parseScopedIdentity({ kind: "profile", connection: "hermes-fixture", profile: "xia" });
if (!key.ok || key.value.kind !== "profile") throw new FixtureRefusal("fixture profile parse failed");
const profile = key.value;
const location = await dependencies.location(profile.connection, {});
const catalog = new ProfileCatalogReader(profile.connection, client, dependencies.metadata(location));
const activity = dependencies.activity();
try {
  await client.ready();
  const running = await client.task("default", "running-001");
  const beforeStatus = await client.task("default", "repeat-001");
  const refusal = await fetch(`${origin}/api/plugins/kanban/tasks/repeat-001?profile=default&board=default`, { method: "PATCH", headers: { ...session.headers, "content-type": "application/json" }, body: JSON.stringify({ status: "running" }), signal: AbortSignal.timeout(5000) });
  const runningAfter = await client.task("default", "repeat-001");
  check("native-direct-running-refusal", running.status === "running" && refusal.status === 400 && runningAfter.status === beforeStatus.status, `nativeStatus=${refusal.status}; seededRunning=${running.status}; unchanged=${runningAfter.status === beforeStatus.status}`);
  const roster = await catalog.roster();
  check("native-roster", ["default", "xia", "empty", "another"].every(name => roster.profiles.some(row => row.profile === name)), `roster count=${roster.profiles.length}; coverage=${roster.coverage.kind}`);
  const skills = await catalog.skills(profile);
  check("accepted-metadata-reader", skills.metadata?.canonicalHome === `${root}/home/profiles/xia` && skills.visible.length === 2 && skills.skills.length >= 2, `visible=${skills.visible.length}; metadataCandidates=${skills.skills.length}; configuration=${skills.metadata?.configuration.status}`);
  const ref = { alias: "hermes-fixture", profileId: "xia", home: `${root}/home/profiles/xia` };
  const cron = await readInspectorCron(dependencies.adapter, ref, {});
  check("owner-scoped-cron", cron.status === "read" && cron.jobs[0]?.source.profileId === "xia", `cron status=${cron.status}; jobs=${cron.jobs.length}; owner=${cron.jobs[0]?.source.profileId}`);
  const history = await readExecutionHistory(dependencies.adapter, ref, { jobId: "qa-owner-cron", limit: 10 });
  check("native-history-reader", history.status === "read" && history.rows.length === 1, `history status=${history.status}; rows=${history.rows.length}`);
  const snapshot = await activity.read({ connection: "hermes-fixture", board: "default", root: location.root, end: Date.now(), preset: 30 }, new AbortController().signal);
  check("native-activity-reader", snapshot.ok && snapshot.value.coverage.kind === "complete", snapshot.ok ? `coverage=${snapshot.value.coverage.kind}` : snapshot.code);
  const documents = dependencies.documents;
  if (!documents) throw new FixtureRefusal("document store missing");
  const before = await documents.read(ref, "SOUL.md");
  if (!before.ok) throw new FixtureRefusal(`SOUL read ${before.code}`);
  const save = await documents.save(ref, "SOUL.md", "Synthetic acceptance saved SOUL.\n", before.value.version, before.value.resolvedPath);
  const after = await documents.read(ref, "SOUL.md");
  check("original-document-helper-save", save.ok && after.ok && after.value.body === "Synthetic acceptance saved SOUL.\n", `save=${save.ok}; authoritativeRead=${after.ok}`);
  await control("external-soul");
  const conflict = await documents.save(ref, "SOUL.md", "Synthetic stale save must fail.\n", save.ok ? save.value.version : null, before.value.resolvedPath);
  check("original-document-helper-conflict", !conflict.ok && conflict.code === "conflict", conflict.ok ? "unexpected save" : conflict.code);
  await control("reset");
  const created = await client.mutate({ route: "POST /tasks", board: "default", body: { title: "QA fixture acceptance", body: "Synthetic body", assignee: "xia" } });
  if (created.kind !== "applied") throw new FixtureRefusal("native create not applied");
  const task = isRecord(created.response.task) ? created.response.task : created.response;
  if (typeof task.id !== "string") throw new FixtureRefusal("created task id missing");
  const id = task.id;
  const reread = await client.task("default", id);
  check("native-create-readback", reread.title === "QA fixture acceptance", `created id=${id}; status=${reread.status}`);
  await control("partial-patch");
  const partial = await client.mutate({ route: "PATCH /tasks/{task_id}", board: "default", id, body: { title: "QA partial persisted", body: "must remain draft" } });
  const actual = await client.task("default", id);
  check("partial-patch-native-commit", partial.kind === "uncertain" && actual.title === "QA partial persisted" && actual.body === "Synthetic body", `result=${partial.kind}; titleCommitted=${actual.title === "QA partial persisted"}; bodyPreserved=${actual.body === "Synthetic body"}`);
  await control("lost-response");
  const lost = await client.mutate({ route: "PATCH /tasks/{task_id}", board: "default", id, body: { title: "QA lost response committed" } });
  const lostActual = await client.task("default", id);
  check("lost-response-native-readback", lost.kind === "uncertain" && lostActual.title === "QA lost response committed", `result=${lost.kind}; committed=${lostActual.title === "QA lost response committed"}`);
  await control("partial-activity");
  const partialActivity = await activity.read({ connection: "hermes-fixture", board: "xia-dev", root: location.root, end: Date.now(), preset: 30 }, new AbortController().signal);
  check("partial-activity", partialActivity.ok && partialActivity.value.coverage.kind === "incomplete", partialActivity.ok ? partialActivity.value.coverage.kind : partialActivity.code);
  await control("unavailable-skills");
  const unavailable = await catalog.skills(profile);
  check("unavailable-skills", unavailable.visibleCoverage.kind === "incomplete" && unavailable.metadata === null, `visibleCoverage=${unavailable.visibleCoverage.kind}; metadataAbsent=${unavailable.metadata === null}`);
  await control("delayed-profile");
  const controller = new AbortController();
  const delayed = catalog.skills(profile, { signal: controller.signal });
  controller.abort();
  let cancelled = false;
  try { await delayed; } catch (error) { if (!(error instanceof Error)) throw error; cancelled = true; }
  check("delayed-profile-cancel", cancelled, `cancelled=${cancelled}`);
  await control("reset");
} finally {
  activity.dispose(); catalog.dispose(); client.dispose(); await lease.release(); await dependencies.connections.dispose();
  writeFileSync(resolve(root, "acceptance.json"), JSON.stringify({ identity, root, origin, cases, pass: cases.length === 14 && cases.every(item => item.pass) }, null, 2));
}
console.log(JSON.stringify({ cases, pass: true }));
